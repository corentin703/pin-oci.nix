//! Nix rendering of a converted compose project. Pure: model in, text out.

use std::collections::BTreeMap;
use std::fmt::Write;

/// A Nix string literal. `${` would start an interpolation and `''`/`\` are escape syntax:
/// a compose value must never be able to run Nix code.
pub(crate) fn string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Service {
    pub(crate) image: String,
    pub(crate) entrypoint: Option<String>,
    pub(crate) cmd: Vec<String>,
    pub(crate) environment: BTreeMap<String, String>,
    pub(crate) labels: BTreeMap<String, String>,
    pub(crate) ports: Vec<String>,
    pub(crate) volumes: Vec<String>,
    pub(crate) depends_on: Vec<String>,
    pub(crate) networks: Vec<String>,
    pub(crate) user: Option<String>,
    pub(crate) workdir: Option<String>,
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Volume {
    pub(crate) external: bool,
    pub(crate) driver: Option<String>,
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Network {
    pub(crate) external: bool,
    pub(crate) internal: bool,
    pub(crate) subnet: Option<String>,
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Project {
    pub(crate) name: String,
    pub(crate) default_network: bool,
    pub(crate) networks: BTreeMap<String, Network>,
    pub(crate) volumes: BTreeMap<String, Volume>,
    pub(crate) services: BTreeMap<String, Service>,
}

fn list(out: &mut String, indent: &str, name: &str, items: &[String]) {
    if items.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}{name} = [");
    for item in items {
        let _ = writeln!(out, "{indent}  {}", string(item));
    }
    let _ = writeln!(out, "{indent}];");
}

fn map(out: &mut String, indent: &str, name: &str, entries: &BTreeMap<String, String>) {
    if entries.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}{name} = {{");
    for (key, value) in entries {
        let _ = writeln!(out, "{indent}  {} = {};", string(key), string(value));
    }
    let _ = writeln!(out, "{indent}}};");
}

fn optional(out: &mut String, indent: &str, name: &str, value: &Option<String>) {
    if let Some(value) = value {
        let _ = writeln!(out, "{indent}{name} = {};", string(value));
    }
}

/// A module that declares the project. Deterministic: names are sorted, field order is fixed.
pub(crate) fn nix(project: &Project, source: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Generated by `pin-oci convert` from {source}.");
    let _ = writeln!(
        out,
        "# Review it, then run `pin-oci lock` to pin the images."
    );
    let _ = writeln!(out, "{{");
    let _ = writeln!(
        out,
        "  virtualisation.pin-oci.projects.{} = {{",
        string(&project.name)
    );
    let _ = writeln!(out, "    enable = true;");
    if project.default_network {
        let _ = writeln!(out, "    networks.default.enable = true;");
    }
    for (name, network) in &project.networks {
        let key = string(name);
        if *network == Network::default() {
            let _ = writeln!(out, "    networks.{key} = {{ }};");
            continue;
        }
        let _ = writeln!(out, "    networks.{key} = {{");
        if network.external {
            let _ = writeln!(out, "      external = true;");
        }
        if network.internal {
            let _ = writeln!(out, "      internal = true;");
        }
        optional(&mut out, "      ", "subnet", &network.subnet);
        let _ = writeln!(out, "    }};");
    }
    for (name, volume) in &project.volumes {
        let key = string(name);
        if *volume == Volume::default() {
            let _ = writeln!(out, "    volumes.{key} = {{ }};");
            continue;
        }
        let _ = writeln!(out, "    volumes.{key} = {{");
        if volume.external {
            let _ = writeln!(out, "      external = true;");
        }
        optional(&mut out, "      ", "driver", &volume.driver);
        let _ = writeln!(out, "    }};");
    }
    for (name, service) in &project.services {
        let _ = writeln!(out, "    services.{} = {{", string(name));
        let indent = "      ";
        let _ = writeln!(out, "{indent}image = {};", string(&service.image));
        optional(&mut out, indent, "entrypoint", &service.entrypoint);
        list(&mut out, indent, "cmd", &service.cmd);
        map(&mut out, indent, "environment", &service.environment);
        map(&mut out, indent, "labels", &service.labels);
        list(&mut out, indent, "ports", &service.ports);
        list(&mut out, indent, "volumes", &service.volumes);
        list(&mut out, indent, "dependsOn", &service.depends_on);
        list(&mut out, indent, "networks", &service.networks);
        optional(&mut out, indent, "user", &service.user);
        optional(&mut out, indent, "workdir", &service.workdir);
        let _ = writeln!(out, "    }};");
    }
    let _ = writeln!(out, "  }};");
    let _ = writeln!(out, "}}");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strings_cannot_open_an_interpolation_or_break_out() {
        assert_eq!(string("plain"), "\"plain\"");
        assert_eq!(string("a\"b"), r#""a\"b""#);
        assert_eq!(string("back\\slash"), r#""back\\slash""#);
        assert_eq!(string("l1\nl2\t\r"), r#""l1\nl2\t\r""#);
        // The dangerous one: `${...}` would run Nix code at evaluation.
        assert_eq!(string("${builtins.exec}"), r#""\${builtins.exec}""#);
        assert_eq!(string("cost: $5 {x}"), "\"cost: $5 {x}\"");
        assert_eq!(string("$${x}"), r#""$\${x}""#);
        assert_eq!(string(""), "\"\"");
    }

    #[test]
    fn a_bare_service_renders_only_its_image() {
        let mut project = Project {
            name: "p".into(),
            ..Project::default()
        };
        project.services.insert(
            "web".into(),
            Service {
                image: "caddy:2-alpine".into(),
                ..Service::default()
            },
        );
        let text = nix(&project, "x.yml");
        assert!(text.contains("projects.\"p\" = {"));
        assert!(text.contains("      image = \"caddy:2-alpine\";\n    };"));
        assert!(!text.contains("networks.default"));
        assert!(!text.contains("ports") && !text.contains("environment"));
    }

    #[test]
    fn output_is_sorted_and_stable() {
        let mut project = Project {
            name: "p".into(),
            ..Project::default()
        };
        for name in ["zeta", "alpha"] {
            project.services.insert(
                name.into(),
                Service {
                    image: "i".into(),
                    environment: BTreeMap::from([
                        ("B".into(), "2".into()),
                        ("A".into(), "1".into()),
                    ]),
                    ..Service::default()
                },
            );
        }
        let text = nix(&project, "x.yml");
        assert!(text.find("\"alpha\"").unwrap() < text.find("\"zeta\"").unwrap());
        assert!(text.find("\"A\" = \"1\"").unwrap() < text.find("\"B\" = \"2\"").unwrap());
        assert_eq!(text, nix(&project, "x.yml"));
    }
}
